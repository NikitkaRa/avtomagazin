    public static int TargetSubscribers(int stopIndex, int stopCount)
    {
        if (stopCount <= 1)
        {
            return 50;
        }

        var t = stopIndex / (double)(stopCount - 1);
        // смесь: равномерно по шкале + пара «горячих» точек
        var baseCount = (int)Math.Round(100 * Math.Pow(t, 1.15));
        if (stopIndex % 17 == 0)
        {
            baseCount = Math.Min(100, baseCount + 25);
        }

        return Math.Clamp(baseCount, 0, 100);
    }

